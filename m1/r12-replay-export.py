"""Round 12: write replay input files for rwxmap into data/r12/replay/<set>/ (gitignored). Refuses to overwrite anything. No training, no Haiku.
Run from the repo root:  .venv/bin/python m1/r12-replay-export.py
Per set: ops.csv (blind ops text, no labels), truth.csv (id,label human truth), p-v020-fp32.jsonl ({id,model,pIsX,pChanges}).
p comes from the exam #4 path: exam4_common.check_models (frozen sha) + exam4_common.probs (ONNX fp32 batch 1, T 0.844) on the inputs.jsonl built by m0/exam3-inputs.mjs.
Truth and input resolution are reused by import from m1/r12-mine.py.
"""
import os, sys, csv, json, shutil, hashlib, importlib.util
REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
sys.path.insert(0, os.path.join(REPO, 'train'))
import numpy as np
import exam4_common as C4
spec = importlib.util.spec_from_file_location('r12mine', os.path.join(REPO, 'm1', 'r12-mine.py'))
M = importlib.util.module_from_spec(spec); spec.loader.exec_module(M)
D = os.path.join(REPO, 'data'); OUT = os.path.join(D, 'r12', 'replay')
SETS = {'exam-2026-11-03-fresh': 'fresh', 'gate-2026-11-03': 'gate1', 'gate-2026-11-04': 'gate2', 'gate-2026-11-06': 'gate3', 'gate-2026-11-07': 'gate4', 'r9-hand': 'r9hand'}
HDR = ['id', 'provider', 'method', 'path', 'operationId', 'summary', 'description']

def main():
    if os.path.exists(OUT): raise SystemExit(f'refusing: {OUT} exists')
    mstr = C4.check_models()['v020-fp32']; m = C4.MODELS['v020-fp32']
    assert mstr == 'rwxlite-0.2.0+8503b655' and m['T'] == 0.844
    from transformers import AutoTokenizer
    tok = AutoTokenizer.from_pretrained(os.path.join(D, 'train', 'ckpt-r8soft', 'final'))
    os.makedirs(OUT)
    for d, name in SETS.items():
        src = M.SETS[name][1]; sd = os.path.join(OUT, d); os.makedirs(sd)
        rows = M.inputs_for(name); truth = M.truth_for(name)
        ops = list(csv.DictReader(open(src, newline='', encoding='utf-8')))
        assert list(ops[0].keys()) == HDR, (d, list(ops[0].keys()))
        assert [r['id'] for r in ops] == [r['id'] for r in rows] and set(truth) == {r['id'] for r in rows}, d
        with open(os.path.join(sd, 'ops.csv'), 'xb') as f, open(src, 'rb') as g: shutil.copyfileobj(g, f)
        with open(os.path.join(sd, 'truth.csv'), 'x', newline='') as f:
            w = csv.writer(f); w.writerow(['id', 'label']); [w.writerow([r['id'], truth[r['id']]]) for r in ops]
        ids = tok([r['text'] for r in rows], truncation=True, max_length=C4.MAXLEN)['input_ids']
        P = C4.probs(os.path.join(m['dir'], m['file']), ids, m['T'])
        pis, pch = P[:, 2], P[:, 1] + P[:, 2]
        assert ((0 <= pis) & (pis <= pch) & (pch <= 1 + 1e-12)).all()
        with open(os.path.join(sd, 'p-v020-fp32.jsonl'), 'x') as f:
            for i, r in enumerate(rows): f.write(json.dumps({'id': r['id'], 'model': mstr, 'pIsX': float(pis[i]), 'pChanges': float(min(pch[i], 1.0))}) + '\n')
        print(d, len(rows), flush=True)
    open(os.path.join(OUT, 'README.txt'), 'x').write(f"""rwxlite replay inputs for rwxmap (round 12). Generated by m1/r12-replay-export.py.
Model string: {mstr} (published 0.2.0 fp32, data/m1/release/model-fp32.onnx), temperature T 0.844.
Per set directory (fresh, gate-2026-11-03/04/06/07, r9-hand):
  ops.csv            id,provider,method,path,operationId,summary,description - the set's blind ops text, byte-copied, no labels.
  truth.csv          id,label (r/w/x) - human truth. gates/fresh: the set's truth.csv; r9-hand: stricter of labels-A/labels-B (as m1/r12-mine.py).
  p-v020-fp32.jsonl  one line per id {{id,model,pIsX,pChanges}}; pIsX = p_x, pChanges = p_w + p_x, calibrated with T 0.844.
p path: exam4_common.probs (ONNX fp32, CPU, batch 1) on inputs built by m0/exam3-inputs.mjs (same text format as exam4), tokenizer max_length 128.
Row order is identical across the three files of a set.
""")
    lines = []
    for dp, _, fs in os.walk(OUT):
        for fn in fs:
            if fn != 'SHA256SUMS': lines.append((os.path.relpath(os.path.join(dp, fn), OUT), hashlib.sha256(open(os.path.join(dp, fn), 'rb').read()).hexdigest()))
    open(os.path.join(OUT, 'SHA256SUMS'), 'x').write(''.join(f'{h}  {p}\n' for p, h in sorted(lines)))

if __name__ == '__main__': main()
