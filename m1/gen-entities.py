"""Generate src/entities.js from Python's html.entities.html5 (run: python3 -I m1/gen-entities.py)."""
import json
import sys
from html.entities import html5

out = ['// GENERATED by m1/gen-entities.py from Python %s html.entities.html5 (%d names). Do not edit.' % (sys.version.split()[0], len(html5)),
       '// Keys keep the trailing ";" where the table has it; the legacy names have an entry without it too.',
       '/** @type {Record<string, string>} */',
       'export const HTML5 = {']
for k in sorted(html5):
    out.append('  %s: %s,' % (json.dumps(k), json.dumps(html5[k], ensure_ascii=True)))
out.append('};')
open('src/entities.js', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(len(html5))
